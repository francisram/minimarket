-- Notas de crédito: comprobante que anula total o parcialmente una factura ya emitida.
-- Tienen su propio timbrado y su propia numeración (serie por punto de expedición).
CREATE TABLE series_nota_credito (
    punto_expedicion_id bigint PRIMARY KEY REFERENCES puntos_expedicion(id),
    timbrado varchar(30),
    timbrado_inicio date,
    timbrado_vencimiento date,
    numero_inicio bigint,
    numero_fin bigint,
    ultimo_numero bigint NOT NULL DEFAULT 0
);

CREATE TABLE notas_credito (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero varchar(30) NOT NULL,
    timbrado varchar(30) NOT NULL,
    timbrado_vencimiento date,
    punto_expedicion_id bigint REFERENCES puntos_expedicion(id),
    pedido_id bigint NOT NULL REFERENCES pedidos(id),
    fecha timestamp(6) NOT NULL,
    motivo varchar(300) NOT NULL,
    reintegra_stock boolean NOT NULL,
    usuario varchar(50) NOT NULL,
    autorizado_por varchar(50),
    total_exentas numeric(12,0) NOT NULL DEFAULT 0,
    total_gravada5 numeric(12,0) NOT NULL DEFAULT 0,
    total_gravada10 numeric(12,0) NOT NULL DEFAULT 0,
    total_iva5 numeric(12,0) NOT NULL DEFAULT 0,
    total_iva10 numeric(12,0) NOT NULL DEFAULT 0,
    total_iva numeric(12,0) NOT NULL DEFAULT 0,
    total numeric(12,0) NOT NULL
);
CREATE UNIQUE INDEX uk_notas_credito_timbrado_numero ON notas_credito (timbrado, numero);
CREATE INDEX idx_notas_credito_pedido ON notas_credito (pedido_id);
CREATE INDEX idx_notas_credito_fecha ON notas_credito (fecha);

CREATE TABLE detalles_nota_credito (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota_credito_id bigint NOT NULL REFERENCES notas_credito(id) ON DELETE CASCADE,
    detalle_pedido_id bigint NOT NULL REFERENCES detalles_pedido(id),
    descripcion varchar(200) NOT NULL,
    cantidad integer NOT NULL,
    precio_unitario numeric(12,0) NOT NULL,
    subtotal numeric(12,0) NOT NULL,
    tipo_iva varchar(20) NOT NULL
);
CREATE INDEX idx_detalles_nc_detalle_pedido ON detalles_nota_credito (detalle_pedido_id);

