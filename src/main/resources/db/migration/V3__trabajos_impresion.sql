-- Cola persistente de impresión (outbox + reintentos + dead letter)
CREATE TABLE trabajos_impresion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo varchar(30) NOT NULL,
    referencia_id bigint NOT NULL,
    impresora_id bigint,
    estado varchar(20) NOT NULL,
    intentos integer NOT NULL,
    max_intentos integer NOT NULL,
    proximo_intento timestamp(6) NOT NULL,
    ultimo_error varchar(500),
    usuario varchar(50),
    fecha_creacion timestamp(6) NOT NULL,
    fecha_actualizacion timestamp(6) NOT NULL
);
CREATE INDEX idx_trabajo_impresion_estado ON trabajos_impresion (estado, proximo_intento);
