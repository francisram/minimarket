-- ============================================================================
-- SCRIPT DE MIGRACIÓN PUENTE (Para bases de datos previas a Flyway / V1)
-- ============================================================================
-- Propósito:
--   Las versiones de hace un mes no contaban con la tabla `puntos_expedicion`
--   ni `movimientos_caja`. Este script prepara de forma segura la estructura
--   existente para que Flyway aplique las versiones V2 a V12 sin interrupciones.
-- ============================================================================

-- 1. Crear tabla puntos_expedicion si no existe
CREATE TABLE IF NOT EXISTS public.puntos_expedicion (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre character varying(100) NOT NULL,
    establecimiento character varying(3) NOT NULL,
    punto_emision character varying(3) NOT NULL,
    timbrado character varying(20),
    timbrado_inicio date,
    timbrado_vencimiento date,
    numero_inicio_factura bigint NOT NULL,
    numero_fin_factura bigint NOT NULL,
    ultimo_numero_factura bigint NOT NULL,
    activo boolean NOT NULL
);

-- Si no hay ningún punto de expedición, creamos el principal con los datos de la institución
INSERT INTO public.puntos_expedicion (
    id, nombre, establecimiento, punto_emision, timbrado, 
    timbrado_inicio, timbrado_vencimiento, 
    numero_inicio_factura, numero_fin_factura, ultimo_numero_factura, activo
)
SELECT 
    1, 
    'Caja 1 - Principal', 
    COALESCE(establecimiento, '001'), 
    COALESCE(punto_emision, '001'), 
    timbrado, 
    timbrado_inicio, 
    timbrado_vencimiento, 
    COALESCE(numero_inicio_factura, 1), 
    COALESCE(numero_fin_factura, 1000), 
    COALESCE(ultimo_numero_factura, 0), 
    true
FROM public.institucion
LIMIT 1
ON CONFLICT (id) DO NOTHING;

-- Sincronizar secuencia si id = 1 fue insertado
SELECT setval('public.puntos_expedicion_id_seq', (SELECT COALESCE(MAX(id), 1) FROM public.puntos_expedicion));

-- 2. Vincular pedidos al punto de expedición
ALTER TABLE public.pedidos ADD COLUMN IF NOT EXISTS punto_expedicion_id bigint REFERENCES public.puntos_expedicion(id);
UPDATE public.pedidos SET punto_expedicion_id = 1 WHERE punto_expedicion_id IS NULL;

-- 3. Columnas en sesiones_caja
ALTER TABLE public.sesiones_caja ADD COLUMN IF NOT EXISTS punto_expedicion_id bigint REFERENCES public.puntos_expedicion(id);
ALTER TABLE public.sesiones_caja ADD COLUMN IF NOT EXISTS total_ingresos_caja numeric(12,0) DEFAULT 0;
ALTER TABLE public.sesiones_caja ADD COLUMN IF NOT EXISTS total_egresos_caja numeric(12,0) DEFAULT 0;
UPDATE public.sesiones_caja SET punto_expedicion_id = 1 WHERE punto_expedicion_id IS NULL;

-- 4. Crear tabla movimientos_caja si no existe
CREATE TABLE IF NOT EXISTS public.movimientos_caja (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monto numeric(12,0) NOT NULL,
    fecha timestamp(6) without time zone NOT NULL,
    sesion_caja_id bigint NOT NULL REFERENCES public.sesiones_caja(id),
    tipo character varying(20) NOT NULL,
    categoria character varying(30) NOT NULL,
    comprobante character varying(50),
    usuario character varying(50) NOT NULL,
    concepto character varying(200) NOT NULL,
    CONSTRAINT movimientos_caja_categoria_check CHECK (((categoria)::text = ANY ((ARRAY['GASTO_MENOR'::character varying, 'RETIRO_EFECTIVO'::character varying, 'PAGO_PROVEEDOR'::character varying, 'CAMBIO_SENCILLO'::character varying, 'OTRO_EGRESO'::character varying, 'INGRESO_EXTRA'::character varying, 'DEVOLUCION_GASTO'::character varying, 'OTRO_INGRESO'::character varying])::text[]))),
    CONSTRAINT movimientos_caja_tipo_check CHECK (((tipo)::text = ANY ((ARRAY['EGRESO'::character varying, 'INGRESO'::character varying])::text[])))
);
CREATE INDEX IF NOT EXISTS idx_mov_caja_fecha ON public.movimientos_caja USING btree (fecha);
CREATE INDEX IF NOT EXISTS idx_mov_caja_sesion ON public.movimientos_caja USING btree (sesion_caja_id);
